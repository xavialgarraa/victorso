const v = process.env.FIREBASE_PRIVATE_KEY || '';
console.log('length:', v.length);
console.log('first char code:', v.charCodeAt(0));
console.log('last char code:', v.charCodeAt(v.length - 1));
console.log('starts with BEGIN marker:', v.startsWith('-----BEGIN'));
console.log('has literal backslash-n (2 chars):', v.includes(String.fromCharCode(92) + 'n'));
console.log('has real newline:', v.includes('\n'));
console.log('has real CRLF:', v.includes('\r\n'));
console.log('has double-escaped backslash-backslash-n:', v.includes('\\\\n'));
const beginIdx = v.indexOf('BEGIN');
console.log('chars around BEGIN (codes):', [...v.slice(Math.max(0, beginIdx - 3), beginIdx + 3)].map((c) => c.charCodeAt(0)));
const endMarkerIdx = v.indexOf('END PRIVATE KEY');
console.log('chars right after END marker line (codes):', [...v.slice(endMarkerIdx, endMarkerIdx + 30)].map((c) => c.charCodeAt(0)));
