export type I18nKey = keyof (typeof I18N)['es'];

const STORAGE_KEY = 'vs_locale';

type TFn = (key: I18nKey, ...args: any[]) => string;

const I18nContext = createContext<{locale: LocaleCode; setLocale: (l: LocaleCode) => void; t: TFn}>({
  locale: 'es',
  setLocale: () => {},
  t: (key) => (I18N.es as Record<string, any>)[key] ?? key,
});

function persistLocaleCookie(next: LocaleCode) {
  // path=/ y un año de validez para que el servidor la lea en cada
  // peticion (SSR y navegaciones) y pida el catalogo ya traducido.
  document.cookie = `${LOCALE_COOKIE}=${next}; path=/; max-age=31536000; SameSite=Lax`;
}

export function I18nProvider({children}: {children: React.ReactNode}) {
  const [locale, setLocaleState] = useState<LocaleCode>('es');
  const revalidator = useRevalidator();

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as LocaleCode | null;
      if (saved && LOCALES[saved]) {
        setLocaleState(saved);
        // Sincroniza la cookie por si el navegador tenía el idioma guardado
        // de antes de que existiera (o se borró, p.ej. modo privado nuevo).
        persistLocaleCookie(saved);
      }
    } catch {
      // localStorage no disponible (modo privado, etc.)
    }
  }, []);

  useEffect(() => {
    document.documentElement.setAttribute('lang', locale);
  }, [locale]);

  function setLocale(next: LocaleCode) {
    setLocaleState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // localStorage no disponible
    }
    persistLocaleCookie(next);
    // Sin esto, el catalogo de Shopify (titulos, descripciones...) se
    // quedaria en el idioma con el que se cargo la pagina hasta la
    // siguiente navegacion — la cookie ya cambió pero los loaders no se
    // vuelven a ejecutar solos.
    void revalidator.revalidate();
  }

  const t: TFn = useMemo(() => {
    const dict = I18N[locale] as Record<string, any>;
    return (key, ...args) => {
      const val = dict[key];
      if (typeof val === 'function') return val(...args);
      return val ?? key;
    };
  }, [locale]);

  const value = useMemo(() => ({locale, setLocale, t}), [locale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
